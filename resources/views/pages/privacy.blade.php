                    <h3>Marketing Website</h3>
                    <p>
                        Our marketing website uses cookies and similar technologies for:
                    </p>
                    <ul>
                        <li><strong>Essential cookies:</strong> Required for website functionality</li>
                        <li><strong>Analytics cookies:</strong> Help us understand how visitors use our site</li>
                        <li><strong>Preference cookies:</strong> Remember your settings and choices</li>
                    </ul>
                    <p>
                        You can control cookies through your browser settings. Disabling cookies may affect
                        website functionality.
                    </p>

                    <h3>Survey Platform</h3>
                    <p>
                        The CEIQ survey platform uses only essential cookies required for the survey to function.
                        We do not use tracking cookies, advertising cookies, or analytics cookies that could
                        identify individual survey respondents.
                    </p>
                </div>

                <div class="legal-section" id="data-security">
                    <h2>8. Data Security</h2>
                    <p>
                        We implement industry-standard security measures to protect data, including:
                    </p>
                    <ul>
                        <li>Encryption of data in transit (TLS/SSL) and at rest</li>
                        <li>Regular security assessments and penetration testing</li>
                        <li>Access controls and authentication requirements</li>
                        <li>Employee training on data protection practices</li>
                        <li>Incident response procedures</li>
                    </ul>
                    <p>
                        While we strive to protect your data, no method of transmission over the Internet is
                        100% secure. We cannot guarantee absolute security but are committed to maintaining
                        appropriate safeguards.
                    </p>
                </div>

                <div class="legal-section" id="retention">
                    <h2>9. Data Retention</h2>
                    <p>
                        We retain data only as long as necessary to fulfill the purposes described in this policy:
                    </p>
                    <ul>
                        <li>
                            <strong>Survey data:</strong> Retained for the duration of the customer's subscription,
                            plus 30 days after termination to allow for data export.
                        </li>
                        <li>
                            <strong>Account data:</strong> Retained while the account is active and for a reasonable
                            period afterward for legal and business purposes.
                        </li>
                        <li>
                            <strong>Aggregated analytics:</strong> May be retained indefinitely as it cannot identify individuals.
                        </li>
                    </ul>
                </div>

                <div class="legal-section" id="childrens-privacy">
                    <h2>10. Children's Privacy</h2>
                    <p>
                        CEIQ is designed for use by educational institutions and adult administrators. Our
                        surveys may be completed by students, but we do not knowingly collect personal
                        information from children under 13 (or the applicable age in your jurisdiction).
                    </p>
                    <p>
                        Because our surveys are anonymous and do not collect PII, student responses cannot
                        be linked to individual children. Schools deploying surveys to students are responsible
                        for ensuring compliance with COPPA, FERPA, and other applicable regulations.
                    </p>

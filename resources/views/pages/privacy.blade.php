                <div class="legal-section" id="commitment">
                    <h2>1. Our Commitment to Privacy</h2>
                    <p>
                        At CEIQ, we believe that meaningful community engagement data can be collected without
                        compromising individual privacy. Our platform was designed from the ground up with
                        privacy as a core principle, not an afterthought.
                    </p>
                    <p>
                        This Privacy Policy explains how we handle information when you use our community
                        engagement intelligence platform. We want to be clear and transparent about our
                        practices so you can make informed decisions.
                    </p>
                </div>

                <div class="legal-section" id="no-pii">
                    <h2>2. Anonymous by Design</h2>

                    <div class="highlight-box">
                        <h3>Key Privacy Commitment</h3>
                        <p>
                            <strong>The CEIQ platform does not collect any personally identifiable information (PII)
                            from survey respondents.</strong> All surveys conducted through our platform are completely
                            anonymous at the individual level. We cannot and do not track, identify, or link survey
                            responses to specific individuals.
                        </p>
                    </div>

                    <p>
                        Our approach to data collection is fundamentally different from traditional survey platforms.
                        We measure community engagement through action-level inventories that capture <em>what</em>
                        happens in school communities, not <em>who</em> is doing it. This design choice ensures that:
                    </p>
                    <ul>
                        <li>Individual survey respondents cannot be identified</li>
                        <li>Responses cannot be traced back to specific students, parents, or staff members</li>
                        <li>No personal information is stored that could be used to re-identify individuals</li>
                        <li>Aggregated data provides valuable insights without privacy risks</li>
                    </ul>
                </div>

                <div class="legal-section" id="what-we-collect">
                    <h2>3. What We Collect</h2>

                    <h3>Survey Responses (Anonymous)</h3>
                    <p>
                        When individuals complete surveys through CEIQ, we collect their responses in a completely
                        anonymous format. This includes:
                    </p>
                    <ul>
                        <li>Responses to survey questions about community engagement activities</li>
                        <li>Optional demographic categories (e.g., role type such as "parent" or "teacher") that cannot identify individuals</li>
                        <li>Timestamp of survey completion (date only, not precise time)</li>
                    </ul>

                    <h3>Administrative Account Information</h3>
                    <p>
                        For school and district administrators who manage CEIQ accounts, we collect:
                    </p>
                    <ul>
                        <li>Name and email address for account creation and login</li>
                        <li>School or district affiliation</li>
                        <li>Role/title within the organization</li>
                        <li>Account activity logs for security purposes</li>
                    </ul>

                    <h3>Website Visitors</h3>
                    <p>
                        When you visit our marketing website (not the survey platform), we may collect:
                    </p>
                    <ul>
                        <li>Information you voluntarily provide through contact forms</li>
                        <li>Basic analytics data (see Cookies & Analytics section)</li>
                    </ul>
                </div>

                <div class="legal-section" id="what-we-dont">
                    <h2>4. What We Don't Collect</h2>

                    <div class="highlight-box">
                        <h3>We Never Collect</h3>
                        <ul>
                            <li>Names, email addresses, or contact information from survey respondents</li>
                            <li>Student ID numbers or other educational record identifiers</li>
                            <li>IP addresses of survey respondents</li>
                            <li>Device fingerprints or tracking identifiers for survey respondents</li>
                            <li>Location data beyond school/district level</li>
                            <li>Social Security numbers or government IDs</li>
                            <li>Financial or health information</li>
                            <li>Any information that could reasonably identify an individual respondent</li>
                        </ul>
                    </div>
                </div>

                <div class="legal-section" id="how-we-use">
                    <h2>5. How We Use Data</h2>

                    <h3>Anonymous Survey Data</h3>
                    <p>We use aggregated, anonymous survey data to:</p>
                    <ul>
                        <li>Generate engagement reports and analytics for subscribing schools and districts</li>
                        <li>Provide benchmarking comparisons across demographic groups</li>
                        <li>Power our EmpowerAI insights and recommendations</li>
                        <li>Improve our platform and develop new features</li>
                        <li>Conduct research on community engagement trends (using only aggregated data)</li>
                    </ul>

                    <h3>Administrative Account Data</h3>
                    <p>We use administrator information to:</p>
                    <ul>
                        <li>Provide access to the CEIQ platform</li>
                        <li>Send service-related communications</li>
                        <li>Provide customer support</li>
                        <li>Send product updates and newsletters (with opt-out option)</li>
                    </ul>
                </div>

                <div class="legal-section" id="data-sharing">
                    <h2>6. Data Sharing</h2>
                    <p>
                        We do not sell, rent, or trade any data to third parties. We may share data only in
                        the following limited circumstances:
                    </p>
                    <ul>
                        <li>
                            <strong>With your organization:</strong> Aggregated survey results are shared with
                            the subscribing school or district that deployed the survey.
                        </li>
                        <li>
                            <strong>Service providers:</strong> We work with trusted vendors who help us operate
                            our platform (hosting, analytics). These providers are contractually bound to protect
                            your data and use it only for providing services to us.
                        </li>
                        <li>
                            <strong>Legal requirements:</strong> We may disclose information if required by law,
                            court order, or government regulation.
                        </li>
                        <li>
                            <strong>Business transfers:</strong> If CEIQ is involved in a merger or acquisition,
                            data may be transferred as part of that transaction, with continued privacy protections.
                        </li>
                    </ul>
                </div>

